TAB3_ARCHITECTURE_TEXT = """
### 1. 資料處理與前處理架構
- **資料特性**：包含 95 個財務特徵欄位，破產類別具高不平衡性。
- **嚴格無洩漏切分**：採 15 折重複分層交叉驗證（5 折 × 3 次重複），切分索引完全固定。
- **前處理管線**：
  1. `FeatureSelector`：檢核原始欄位完整性。
  2. `DropConstantAndDuplicate`：排除常數欄位與完全共線性重複欄位。
  3. `QuantileScaler`：將特徵分位數映射至常態分布，穩定極端離群值影響。
  4. `CorrelationFilter`：於訓練折內貪婪過濾高度線性相關特徵（$|r| > 0.95$），最終保留 72 個特徵送入基底分類器。

### 2. 三模型集成與百分位平均機制
- **基底模型**：
  - **M3 (ExtraTrees)**：極端隨機樹分類器。
  - **M4 (XGBoost)**：梯度提升樹分類器。
  - **M5 (LightGBM)**：輕量梯度提升機。
- **集成評分機制 (E_A)**：
  三個基底模型各自預測破產機率後，不直接加總原始機率（因各模型校準尺度與長尾斜率不同），
  而是將原始輸出分別與該模型在訓練階段固化之參考經驗累積分布函數（ECDF）比對，
  轉換為 0～1 之經驗百分位排序後，再取等權平均：
  $$\\text{Score}_{E_A} = \\frac{1}{3}\\left(P_{\\text{ref,M3}}(S_{\\text{M3}}) + P_{\\text{ref,M4}}(S_{\\text{M4}}) + P_{\\text{ref,M5}}(S_{\\text{M5}})\\right)$$

### 3. 工作點固化與安全邊際策略
為避免在極端不平衡情境下因模型漂移導致漏抓關鍵破產企業，本系統在連續百分位集成排名上固化四個營運工作點。
為因應交叉驗證跨折轉移時的門檻波動，在目標召回率基礎上納入**安全邊際**（$m$）：
- 目標召回提高至 $R' = \\min(1.0, R + m)$，確保在獨立驗證時達標率不低於預期標準。
"""

