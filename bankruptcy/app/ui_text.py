def format_score_summary(score_sentence: str, share_ge: float) -> str:
    pct = share_ge * 100.0
    return (
        f"**{score_sentence}**\n\n"
        f"在全體訓練資料之參考分布中，約有 **{pct:.2f}%** 的樣本風險分數大於或等於此數值。"
    )


def format_platt_note(prob: float, base_rate: float) -> str:
    prob_pct = prob * 100.0
    base_pct = base_rate * 100.0
    return (
        f"校準後驗機率：**{prob_pct:.2f}%**\n\n"
        f"（註：Platt Scaling 係針對本訓練資料之基準破產率（約 {base_pct:.2f}%）進行單調勝算轉換；"
        "此數值反映樣本在訓練資料分布下的後驗機率，絕不代表真實商業市場之絕對破產發生機率。）"
    )


def format_range_warning_message(feature: str, val: float, p01: float, p99: float) -> str:
    return (
        f"【常見範圍警示】特徵 {feature} 目前輸入值（{val:.4g}）已超出訓練資料常见範圍 "
        f"[p01: {p01:.4g}, p99: {p99:.4g}]。"
    )


def format_out_of_range_message(feature: str, val: float, f_min: float, f_max: float) -> str:
    return (
        f"【全距超出警示】特徵 {feature} 目前輸入值（{val:.4g}）已完全超出訓練資料全距 "
        f"[min: {f_min:.4g}, max: {f_max:.4g}]，外推推論結果極度不可靠！"
    )


